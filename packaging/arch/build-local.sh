#!/usr/bin/env bash
# Assemble the package without makepkg (same layout makepkg produces).
# Prefer `makepkg` on a real Arch system; this exists for environments without it.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
src=$(cd "$here/../.." && pwd)
out=${1:-$src/dist}
. "$here/PKGBUILD"

work=$(mktemp -d)
pkgdir="$work/pkg"
mkdir -p "$pkgdir"
startdir="$here"
package

cp "$here/$install" "$pkgdir/.INSTALL"
size=$(du -sb --exclude=.INSTALL "$pkgdir" | cut -f1)
{
    echo "# Generated by build-local.sh"
    echo "pkgname = $pkgname"
    echo "pkgbase = $pkgname"
    echo "xdata = pkgtype=pkg"
    echo "pkgver = $pkgver-$pkgrel"
    echo "pkgdesc = $pkgdesc"
    echo "url = $url"
    echo "builddate = $(date +%s)"
    echo "packager = niruxxdaboi"
    echo "size = $size"
    echo "arch = $arch"
    for l in "${license[@]}"; do echo "license = $l"; done
    for d in "${depends[@]}"; do echo "depend = $d"; done
    for d in "${optdepends[@]}"; do echo "optdepend = $d"; done
} > "$pkgdir/.PKGINFO"

cd "$pkgdir"
# every path, like makepkg (bsdtar -n does not recurse)
files=$(find . -mindepth 1 -printf '%P\n' | grep -v '^\.PKGINFO$\|^\.INSTALL$\|^\.MTREE$' | LC_ALL=C sort)
LANG=C bsdtar --uid 0 --gid 0 --uname root --gname root -czf .MTREE --format=mtree \
    --options='!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link' \
    .PKGINFO .INSTALL $files
mkdir -p "$out"
pkg="$out/$pkgname-$pkgver-$pkgrel-$arch.pkg.tar.zst"
LANG=C bsdtar --uid 0 --gid 0 --uname root --gname root -cnf - .MTREE .PKGINFO .INSTALL $files \
    | zstd -c -T0 -19 -q > "$pkg"
rm -rf "$work"
echo "$pkg"
